# -*- coding: utf-8 -*-
"""사내근로복지기금 법인세 글의 대표 그림. 돈 계산형이라 비교표가 중심이다."""
import sys
from PIL import Image, ImageDraw, ImageFont

sys.stdout.reconfigure(encoding='utf-8')

W, H, S = 1200, 630, 2
남색 = (31, 56, 100)
금색 = (196, 165, 105)
배경 = (254, 254, 254)
연회색 = (244, 246, 250)
줄색 = (222, 229, 240)
글자 = (26, 29, 37)
흐린글자 = (98, 107, 120)

굵게 = 'C:/Windows/Fonts/malgunbd.ttf'
보통 = 'C:/Windows/Fonts/malgun.ttf'
F = {}


def f(굵음, 크기):
    key = (굵음, 크기)
    if key not in F:
        F[key] = ImageFont.truetype(굵게 if 굵음 else 보통, 크기 * S)
    return F[key]


im = Image.new('RGB', (W * S, H * S), 배경)
d = ImageDraw.Draw(im)


def 글(x, y, t, 크기=17, 굵음=False, 색=글자, 맞춤='la'):
    d.text((x * S, y * S), t, font=f(굵음, 크기), fill=색, anchor=맞춤)


def 상자(x1, y1, x2, y2, 반지름=10, 채움=None, 선=None, 두께=1):
    d.rounded_rectangle(
        (x1 * S, y1 * S, x2 * S, y2 * S), radius=반지름 * S,
        fill=채움, outline=선, width=두께 * S,
    )


# ── 머리 ───────────────────────────────────────────────
d.rectangle((0, 0, W * S, 100 * S), fill=남색)
글(60, 50, '5천만원 출연하면 세금이 얼마나 줄까', 34, True, (255, 255, 255), 'lm')
글(1140, 50, '과세표준 3억원 · 2026년 세율 기준', 16, False, (196, 207, 226), 'rm')

# ── 표 ─────────────────────────────────────────────────
좌, 가운데, 오른쪽 = 60, 700, 1000
표위 = 148

글(좌 + 24, 표위, '', 15)
글(가운데, 표위, '출연하지 않으면', 16, True, 흐린글자, 'mb')
글(오른쪽, 표위, '5천만원 출연하면', 16, True, 남색, 'mb')

행 = [
    ('과세표준', '3억원', '2억 5천만원', False),
    ('법인세', '4,000만원', '3,000만원', False),
    ('지방소득세', '400만원', '300만원', False),
    ('세금 합계', '4,400만원', '3,300만원', True),
]
y = 표위 + 22
for 이름, 왼, 오른, 강조 in 행:
    높이 = 58 if 강조 else 50
    if 강조:
        상자(좌, y, 1140, y + 높이, 8, 연회색)
    else:
        d.line(((좌 * S, (y + 높이) * S), (1140 * S, (y + 높이) * S)), fill=줄색, width=1 * S)
    가온 = y + 높이 / 2
    글(좌 + 24, 가온, 이름, 18 if 강조 else 17, 강조, 남색 if 강조 else 글자, 'lm')
    글(가운데, 가온, 왼, 19 if 강조 else 18, 강조, 흐린글자, 'mm')
    글(오른쪽, 가온, 오른, 21 if 강조 else 18, True, 남색, 'mm')
    y += 높이 + 4

# ── 결과 띠 ────────────────────────────────────────────
띠 = y + 26
상자(60, 띠, 1140, 띠 + 66, 10, 남색)
글(96, 띠 + 33, '줄어든 세금', 17, False, (196, 207, 226), 'lm')
글(300, 띠 + 33, '1,100만원', 30, True, 금색, 'lm')
글(1116, 띠 + 33, '출연금 5천만원 × 22%  (법인세 20% + 지방소득세)', 16, False, (196, 207, 226), 'rm')

# ── 아래 한 줄 ─────────────────────────────────────────
글(60, 띠 + 106, '다만 나간 돈은 5천만원입니다. 실제 차이는 그 돈을 근로자가 받을 때 생깁니다.', 17, False, 글자)

글(1140, 600, '노무법인 도원', 17, True, 남색, 'rm')

밖 = 'C:/Users/owner/Desktop/★업무/dowon-blog/content/posts/기금-법인세-얼마나-줄어드나/1.webp'
