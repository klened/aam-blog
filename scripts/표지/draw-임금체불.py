def f(굵음, 크기):
    key = (굵음, 크기)
    if key not in F:
        F[key] = ImageFont.truetype(굵게 if 굵음 else 보통, 크기 * S)
    return F[key]


def 새판(제목, 오른쪽):
    im = Image.new('RGB', (W * S, H * S), 배경)
    d = ImageDraw.Draw(im)
    d.rectangle((0, 0, W * S, 100 * S), fill=남색)
    d.text((60 * S, 50 * S), 제목, font=f(True, 34), fill=(255, 255, 255), anchor='lm')
    d.text((1140 * S, 50 * S), 오른쪽, font=f(False, 16), fill=(196, 207, 226), anchor='rm')
    return im, d


def 저장(im, 폴더):
    im.resize((W, H), Image.LANCZOS).save(ROOT + 폴더 + '/1.webp', 'WEBP', quality=92, method=6)
    print('  ', 폴더)


def 글(d, x, y, t, 크기=17, 굵음=False, 색=글자, 맞춤='la'):
    d.text((x * S, y * S), t, font=f(굵음, 크기), fill=색, anchor=맞춤)


def 상자(d, x1, y1, x2, y2, 반지름=10, 채움=None, 선=None, 두께=1):
    d.rounded_rectangle((x1 * S, y1 * S, x2 * S, y2 * S), radius=반지름 * S,
                        fill=채움, outline=선, width=두께 * S)


def 세줄판(제목, 오른쪽, 줄들, 아래줄, 폴더, 강조색=None):
    """조건 → 결과 세 줄을 쌓는 판."""
    im, d = 새판(제목, 오른쪽)
    y = 152
    for i, (왼, 오른칸, 색) in enumerate(줄들):
        높이 = 96
        상자(d, 60, y, 1140, y + 높이, 10, 연회색)
        상자(d, 60, y, 66, y + 높이, 3, 색)
        글(d, 96, y + 높이 / 2, 왼, 20, True, 글자, 'lm')
        글(d, 620, y + 높이 / 2, 오른칸, 20, True, 색, 'lm')
        y += 높이 + 16
    글(d, 60, y + 26, 아래줄[0], 18, True, 금색)
    for j, 줄 in enumerate(아래줄[1:]):
        글(d, 60, y + 66 + j * 32, 줄, 17, False, 글자)
    글(d, 1140, 600, '노무법인 도원', 17, True, 남색, 'rm')
    저장(im, 폴더)


