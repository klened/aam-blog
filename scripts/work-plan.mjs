function 사본읽기() {
  if (!fs.existsSync(사본)) return []
  const 표 = csv읽기(fs.readFileSync(사본, 'utf-8'))
  const 머리 = 표[0].map((h) => h.trim())
  if (!머리.includes('키워드')) return []   // 옛 형식이면 버린다
  return 표.slice(1)
    .map((r) => Object.fromEntries(머리.map((h, n) => [h, (r[n] ?? '').trim()])))
    .filter((o) => o.키워드)
    .map((o) => ({ ...o, 검색량: 검색량읽기(o.검색량) }))
}

