/** 따옴표 안의 쉼표와 줄바꿈을 지킨다. 콘텐츠 제목에 쉼표가 흔하다. */
function csv읽기(글자) {
  const 표 = []
  let 줄 = []
  let 칸 = ''
  let 따옴표 = false
  const s = 글자.replace(/^\uFEFF/, '')
  for (let i = 0; i < s.length; i += 1) {
    const c = s[i]
    if (따옴표) {
      if (c !== '"') 칸 += c
      else if (s[i + 1] === '"') { 칸 += '"'; i += 1 }
      else 따옴표 = false
    } else if (c === '"') 따옴표 = true
    else if (c === ',') { 줄.push(칸); 칸 = '' }
    else if (c === '\n') { 줄.push(칸); 표.push(줄); 줄 = []; 칸 = '' }
    else if (c !== '\r') 칸 += c
  }
  if (칸 || 줄.length) { 줄.push(칸); 표.push(줄) }
  return 표
}

const 칸감싸기 = (v) => (/[",\n]/.test(String(v ?? '')) ? `"${String(v).replace(/"/g, '""')}"` : String(v ?? ''))
const csv쓰기 = (표) => 표.map((r) => r.map(칸감싸기).join(',')).join('\r\n')

