#!/usr/bin/env node
/**
 * 원고 문체 검사.
 *
 *   node 문체검사.mjs 원고.txt
 *   node 문체검사.mjs 원고.txt --전체     (건너뛴 줄까지 다 본다)
 *
 * 세 층으로 나눈다. 층을 섞으면 경고가 많아 아무도 안 읽게 된다.
 *
 *   A 확정   기계가 확실히 아는 것. 고치지 않으면 검사가 실패한다.
 *   B 경고   기계는 의심만 한다. 사람이 보고 판단한다.
 *   C 확인   기계가 못 푸는 것. 볼 자리만 짚어 준다.
 *
 * C 층이 있는 이유가 이 도구의 요점이다. 2026-08-08 에 「단종 부품 문제를
 * 해결한다」를 줄이다가 「단종 부품, 이렇게 푼다」로 써서 부품이 「푸는」
 * 대상이 되었다. 이런 호응 오류는 금지어 목록에 걸리지 않는다. 「푼다」는
 * 금지어가 아니기 때문이다. 그래서 잡으려 들지 않고 사람에게 넘긴다.
 *
 * 국립국어원 「한눈에 알아보는 공공언어 바로 쓰기(개정판)」의 부록 목록
 * (행정용어 100개, 일본어 투 50개)은 넣지 않았다. 공문서용이라 산업 글에는
 * 안 맞는다. 그 목록대로면 「드론」을 「무인기」로 바꿔야 하는데, 그러면
 * 검색으로 들어오는 길이 끊긴다. 대신 같은 책 본문의 문형 규칙만 가져왔다.
 */

import fs from 'node:fs'
