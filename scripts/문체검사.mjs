/* ── 검사에서 빼는 줄 ────────────────────────────────────────────────
   원고 파일에는 본문 말고도 제목안, 이미지 계획, 발행 전 확인이 같이 있다.
   그것까지 세면 경고가 본문보다 많아진다. */
const 건너뛸줄 = [
  /^\s*$/,                    // 빈 줄
  /^[■□▶·※]/,                // 메모·안내 기호로 시작
  /^\s*→/,                    // 보충 설명
  /^\[/,                      // [이미지 1 — ...]
  /^={3,}|^─{3,}|^-{3,}/,     // 구분선
  /[┌│└├┬┼┤┐┘]/,             // 표 괘선
  /^https?:\/\//,             // 주소만 있는 줄
  /^📞|^✉/,                   // 연락처
  /^\d+\)\s/,                 // 1) 제목안
]

