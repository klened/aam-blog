/**
 * 애널리틱스에 사건 하나를 보낸다.
 *
 * 조회수는 이미 두 군데에서 세고 있다. 여기서 세려는 것은 그게 아니라
 * **읽은 사람이 상담으로 갔는가**다. 지금은 이 자리가 비어 있어서, 글이
 * 문의를 만들었는지 아닌지를 알 방법이 없다. 채널톡에 찍히는 유입경로는
 * 탈리폼과 Zapier 를 거치면서 원래 출처가 끊겨 근거로 쓸 수 없다.
 *
 * 태그가 아직 안 실렸거나 차단기에 막혔으면 조용히 넘어간다. 통계 한 줄
 * 못 보낸 것 때문에 버튼이 안 눌리는 편이 훨씬 나쁘다.
 *
 * **이름과 매개변수 키는 영문·숫자·밑줄로, 문자로 시작하게 쓴다.** 한글로
 * 보내면 GA4 가 조용히 버린다. gtag 는 오류를 내지 않아서 보낸 쪽에서는
 * 성공한 것처럼 보이고, 실시간 보고서를 열어 봐야 없는 것을 알게 된다.
 * 값은 한글이어도 된다.
 */
declare global {
  interface Window {
    gtag?: (...args: unknown[]) => void
  }
}

export function 사건보내기(이름: string, 값: Record<string, unknown> = {}) {
  if (typeof window === 'undefined') return
  try {
    window.gtag?.('event', 이름, 값)
  } catch {
    // 통계는 실패해도 화면이 하던 일을 계속해야 한다.
  }
}
